from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from backend.app.database.session import get_db
from backend.app.models.entities import Prediction, Hospital, ModelRecord, User, AuditLog
from backend.app.schemas.prediction import PredictionRequest, PredictionOut
from backend.app.ml.preprocessor import DataPreprocessor
from backend.app.ml.dataset_config import DEFAULT_HEART_DISEASE_CONFIG
from backend.app.federated.coordinator import FederatedCoordinator
from backend.app.api.deps import get_current_user

router = APIRouter(prefix="/predictions", tags=["Disease Prediction"])

DISCLAIMER_TEXT = (
    "ACADEMIC RESEARCH PROTOTYPE ONLY: This prediction is generated by an experimental "
    "collaborative federated learning model for educational and demonstration purposes. "
    "It does not constitute an approved clinical diagnosis or medical device and must NOT "
    "be used for patient care or clinical decision-making."
)

@router.post("", response_model=PredictionOut)
def predict_disease_risk(
    req: PredictionRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    coordinator = FederatedCoordinator(db)
    
    # Select requested model version or default to active global model
    if req.model_version and req.model_version != "global_latest":
        model_rec = db.query(ModelRecord).filter(ModelRecord.model_version == req.model_version).first()
        if not model_rec:
            raise HTTPException(status_code=404, detail=f"Model version '{req.model_version}' not found")
        weights = model_rec.parameters_summary.get("weights", [0.0] * len(DEFAULT_HEART_DISEASE_CONFIG.feature_columns))
        bias = model_rec.parameters_summary.get("bias", 0.0)
        classifier = coordinator.global_classifier
        classifier.set_parameters(weights, bias)
    else:
        model_rec, classifier = coordinator.get_latest_global_model()

    preprocessor = DataPreprocessor(DEFAULT_HEART_DISEASE_CONFIG)
    scaled_vector = preprocessor.transform_single_record(req.features)

    # Compute probability & prediction
    probabilities = classifier.predict_proba(scaled_vector)[0]
    prob_healthy = float(probabilities[0])
    prob_risk = float(probabilities[1])

    result_label = (
        DEFAULT_HEART_DISEASE_CONFIG.target_positive_label
        if prob_risk >= 0.50
        else DEFAULT_HEART_DISEASE_CONFIG.target_negative_label
    )
    confidence = prob_risk if prob_risk >= 0.50 else prob_healthy

    # Hospital association
    hosp_id = req.hospital_id or current_user.hospital_id
    hosp_name = None
    if hosp_id:
        hosp = db.query(Hospital).filter(Hospital.id == hosp_id).first()
        if hosp:
            hosp_name = hosp.hospital_name

    # Save in database
    prediction_rec = Prediction(
        hospital_id=hosp_id,
        model_version=model_rec.model_version,
        input_features=req.features,
        prediction_result=result_label,
        confidence=round(confidence, 4)
    )
    db.add(prediction_rec)

    # Audit log
    audit = AuditLog(
        user_id=current_user.id,
        action="PREDICTION_PERFORMED",
        resource=f"Model {model_rec.model_version}",
        status="SUCCESS",
        metadata_json={
            "result": result_label,
            "confidence": round(confidence, 4),
            "model_version": model_rec.model_version
        }
    )
    db.add(audit)
    db.commit()
    db.refresh(prediction_rec)

    return PredictionOut(
        id=prediction_rec.id,
        hospital_id=hosp_id,
        hospital_name=hosp_name,
        model_version=model_rec.model_version,
        prediction_result=result_label,
        confidence=round(confidence, 4),
        probability_risk=round(prob_risk, 4),
        probability_healthy=round(prob_healthy, 4),
        input_features=req.features,
        disclaimer=DISCLAIMER_TEXT,
        created_at=prediction_rec.created_at
    )

@router.get("/history", response_model=List[PredictionOut])
def get_prediction_history(
    hospital_id: Optional[int] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    query = db.query(Prediction)
    if current_user.role in ("HOSPITAL_ADMIN", "DOCTOR") and current_user.hospital_id:
        query = query.filter(Prediction.hospital_id == current_user.hospital_id)
    elif hospital_id:
        query = query.filter(Prediction.hospital_id == hospital_id)

    preds = query.order_by(Prediction.id.desc()).limit(100).all()
    results = []
    for p in preds:
        hosp_name = p.hospital.hospital_name if p.hospital else None
        prob_risk = p.confidence if "Risk Detected" in p.prediction_result else (1.0 - p.confidence)
        prob_healthy = 1.0 - prob_risk
        results.append(PredictionOut(
            id=p.id,
            hospital_id=p.hospital_id,
            hospital_name=hosp_name,
            model_version=p.model_version,
            prediction_result=p.prediction_result,
            confidence=p.confidence,
            probability_risk=round(prob_risk, 4),
            probability_healthy=round(prob_healthy, 4),
            input_features=p.input_features,
            disclaimer=DISCLAIMER_TEXT,
            created_at=p.created_at
        ))
    return results
