import { Router, Request, Response } from 'express';
import { db } from '../db/database';
import { store, PredictionEntity } from '../db/store';
import { FederatedEngine } from '../fl/engine';
import { requireAuth } from '../middleware/auth';

export const predictionsRouter = Router();

const FEATURE_NAMES = [
  'age',
  'sex',
  'chest_pain_type',
  'resting_bp',
  'cholesterol',
  'fasting_blood_sugar',
  'resting_ecg',
  'max_heart_rate',
  'exercise_angina',
  'st_depression',
];

predictionsRouter.post('/', requireAuth, async (req: Request, res: Response) => {
  const { hospital_id, model_version, features } = req.body;
  const currentUser = req.user!;

  if (!features || typeof features !== 'object') {
    return res.status(400).json({ detail: 'features dictionary is required' });
  }

  // Find active model or model by version
  let targetModel = store.models.find((m) => m.model_version === model_version);
  if (!targetModel) {
    targetModel = store.models.find((m) => m.is_active) || store.models[0];
  }

  const weights = targetModel?.parameters_summary?.weights || new Array(10).fill(0);
  const bias = targetModel?.parameters_summary?.bias || 0;

  // Extract ordered features
  const featureVector = FEATURE_NAMES.map((fn) => {
    const val = features[fn];
    return typeof val === 'number' ? val : 0;
  });

  const probabilityRisk = FederatedEngine.predictProbability(featureVector, { weights, bias });
  const probabilityHealthy = 1.0 - probabilityRisk;
  const isHighRisk = probabilityRisk >= 0.5;
  const confidence = Number(Math.max(probabilityRisk, probabilityHealthy).toFixed(4));

  const effectiveHospitalId = hospital_id || currentUser.hospital_id || 1;
  const hospital = effectiveHospitalId ? store.hospitals.find((h) => h.id === effectiveHospitalId) : undefined;

  const predictionResultStr = isHighRisk
    ? 'Positive Risk (High Cardiac Event Probability)'
    : 'Negative Risk (Normal / Low Cardiac Event Risk)';

  const result: PredictionEntity = {
    id: store.predictions.length + 1,
    hospital_id: effectiveHospitalId,
    hospital_name: hospital?.hospital_name,
    model_version: targetModel.model_version,
    prediction_result: predictionResultStr,
    confidence,
    probability_risk: Number(probabilityRisk.toFixed(4)),
    probability_healthy: Number(probabilityHealthy.toFixed(4)),
    input_features: features,
    disclaimer:
      'CONFIDENTIAL MEDICAL DECISION SUPPORT PROTOTYPE: This prediction is generated by a collaborative privacy-preserving federated learning model. It is intended for experimental clinical research only and does not replace certified diagnostic medical evaluations.',
    created_at: new Date().toISOString(),
  };

  try {
    await db.execute(
      `INSERT INTO predictions (hospital_id, model_version, input_features, prediction_result, confidence, created_at)
       VALUES ($1, $2, $3, $4, $5, CURRENT_TIMESTAMP)`,
      [
        effectiveHospitalId,
        targetModel.model_version,
        JSON.stringify(features),
        predictionResultStr,
        confidence,
      ]
    );

    await db.execute(
      `INSERT INTO audit_logs (user_id, action, resource, status, timestamp, metadata_json)
       VALUES ($1, $2, $3, $4, CURRENT_TIMESTAMP, $5)`,
      [
        currentUser.id,
        'MODEL_PREDICTION',
        `Inference via ${targetModel.model_version}`,
        'SUCCESS',
        JSON.stringify({
          risk: isHighRisk ? 'HIGH' : 'LOW',
          confidence,
          hospital_id: effectiveHospitalId,
        }),
      ]
    );
  } catch (err) {
    console.error('[Predictions] Error saving prediction to DB:', err);
  }

  store.predictions.unshift(result);
  store.logAudit(
    'MODEL_PREDICTION',
    `Inference via ${targetModel.model_version}`,
    'SUCCESS',
    { id: currentUser.id, name: currentUser.name },
    {
      risk: isHighRisk ? 'HIGH' : 'LOW',
      prob_risk: result.probability_risk,
      hospital_id: effectiveHospitalId,
    }
  );

  return res.json(result);
});

predictionsRouter.get('/', requireAuth, (req: Request, res: Response) => {
  const hospitalId = req.query.hospital_id ? parseInt(req.query.hospital_id as string, 10) : undefined;
  if (hospitalId) {
    return res.json(store.predictions.filter((p) => p.hospital_id === hospitalId));
  }
  return res.json(store.predictions);
});

predictionsRouter.get('/history', requireAuth, (req: Request, res: Response) => {
  const hospitalId = req.query.hospital_id ? parseInt(req.query.hospital_id as string, 10) : undefined;
  if (hospitalId) {
    return res.json(store.predictions.filter((p) => p.hospital_id === hospitalId));
  }
  return res.json(store.predictions);
});
